MEDIATION_MEDIATOR_FORMULA = "scaled_saturation ~ RF_ordinal*C(pooling)"
MEDIATION_OUTCOME_FORMULA = "scaled_delta ~ (scaled_saturation + RF_ordinal + C(pooling))**2"
MEDIATION_MEDIATOR_FORMULA_REDUCED = "scaled_saturation ~ RF_ordinal"
MEDIATION_OUTCOME_FORMULA_REDUCED = "scaled_delta ~ scaled_saturation*RF_ordinal"
