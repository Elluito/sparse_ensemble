def mediation_joint_tests(d):
    """
    Task 2: nested-model F-tests for the pooling terms in each model and for all saturation (x) terms in the
    outcome model.
    """
    mediator_full = smf.ols(MEDIATION_MEDIATOR_FORMULA, d).fit()
    mediator_reduced = smf.ols(MEDIATION_MEDIATOR_FORMULA_REDUCED, d).fit()
    outcome_full = smf.ols(MEDIATION_OUTCOME_FORMULA, d).fit()
    outcome_reduced = smf.ols(MEDIATION_OUTCOME_FORMULA_REDUCED, d).fit()
    outcome_no_x = smf.ols("scaled_delta ~ RF_ordinal*C(pooling)", d).fit()
    mediator_additive = smf.ols(MEDIATION_MEDIATOR_FORMULA_ADDITIVE, d).fit()
    outcome_additive = smf.ols(MEDIATION_OUTCOME_FORMULA_ADDITIVE, d).fit()

    tests = [
        ("Mediator: all pooling terms (x~y*z vs x~y)", mediator_full, mediator_reduced),
        ("Mediator: pooling main effects (x~y+z vs x~y)", mediator_additive, mediator_reduced),
        ("Mediator: pooling interactions (x~y*z vs x~y+z)", mediator_full, mediator_additive),
        ("Outcome: all pooling terms ((x+y+z)**2 vs x*y)", outcome_full, outcome_reduced),
        ("Outcome: pooling main effects (x*y+z vs x*y)", outcome_additive, outcome_reduced),
        ("Outcome: pooling interactions ((x+y+z)**2 vs x*y+z)", outcome_full, outcome_additive),
        ("Outcome: all saturation terms ((x+y+z)**2 vs y*z)", outcome_full, outcome_no_x),
        ("Outcome reduced: saturation terms (x*y vs y)", outcome_reduced, smf.ols("scaled_delta ~ RF_ordinal", d).fit()),
    ]
    rows = []
    for name, full, restricted in tests:
        f_value, p_value, df_diff = full.compare_f_test(restricted)
        rows.append({"test": name, "F": f_value, "p": p_value, "df_num": df_diff, "df_den": full.df_resid,
                     "R2 full": full.rsquared, "R2 restricted": restricted.rsquared})
    return pd.DataFrame(rows).set_index("test")


def saturation_slope_contrast(fitted_model, y, pooling_levels=None):
    """
    Contrast vector for the slope of scaled_saturation on scaled_delta at RF_ordinal = y.
    pooling_levels=None gives the slope at the reference pooling level; a list of levels averages the slope over
    them with equal weights (the reference level contributes a zero interaction).
    """
    names = list(fitted_model.params.index)
    contrast = np.zeros(len(names))
    for i, name in enumerate(names):
        parts = name.split(":")
        if "scaled_saturation" not in parts:
            continue
        others = [p for p in parts if p != "scaled_saturation"]
        if not others:
            contrast[i] = 1.0
        elif others == ["RF_ordinal"]:
            contrast[i] = y
        elif len(others) == 1 and others[0].startswith("C(pooling)") and pooling_levels is not None:
            level = others[0].split("[T.")[1].rstrip("]")
            contrast[i] = (level in pooling_levels) / len(pooling_levels)
    return contrast


def mediation_conditional_slopes(d, ys=(-1.0, 0.0, 1.0)):
    """Task 3: slope of saturation on Δ at RF_ordinal = -1, 0, +1 with 95% CIs."""
    pooling_levels = sorted(d["pooling"].unique())
    fits = {"full": smf.ols(MEDIATION_OUTCOME_FORMULA, d).fit(),
            "reduced": smf.ols(MEDIATION_OUTCOME_FORMULA_REDUCED, d).fit(),
            "additive": smf.ols(MEDIATION_OUTCOME_FORMULA_ADDITIVE, d).fit()}
    rows = []
    for model_name, fitted_model in fits.items():
        averages = [("reference pooling", None)]
        if model_name == "full":
            averages.append(("averaged over pooling", pooling_levels))
        for pooling_label, levels in averages:
            for y in ys:
                test = fitted_model.t_test(saturation_slope_contrast(fitted_model, y, levels))
                ci = np.asarray(test.conf_int()).ravel()
                rows.append({"model": model_name, "pooling": pooling_label, "RF_ordinal": y,
                             "slope": float(np.squeeze(test.effect)), "se": float(np.squeeze(test.sd)),
                             "p": float(np.squeeze(test.pvalue)), "ci_low": ci[0], "ci_high": ci[1]})
    return pd.DataFrame(rows)


def mediation_effects(d, mediator_formula=MEDIATION_MEDIATOR_FORMULA, outcome_formula=MEDIATION_OUTCOME_FORMULA,
                      contrasts=MEDIATION_CONTRASTS):
    """
    NDE / NIE / TE (VanderWeele convention) for RF_ordinal moving y0 -> y1, averaged over the pooling levels:
    NDE = Δ(y1, x(y0)) - Δ(y0, x(y0)), NIE = Δ(y1, x(y1)) - Δ(y1, x(y0)), TE = NDE + NIE.
    """
    m = smf.ols(mediator_formula, d).fit()
    o = smf.ols(outcome_formula, d).fit()
    P = pd.DataFrame({"pooling": sorted(d["pooling"].unique())})
    f = lambda y, x: o.predict(P.assign(RF_ordinal=y, scaled_saturation=x)).mean()
    effects = {}
    for y0, y1 in contrasts:
        x0 = m.predict(P.assign(RF_ordinal=y0)).values
        x1 = m.predict(P.assign(RF_ordinal=y1)).values
        effects[(y0, y1, "NDE")] = f(y1, x0) - f(y0, x0)
        effects[(y0, y1, "NIE")] = f(y1, x1) - f(y1, x0)
        effects[(y0, y1, "TE")] = f(y1, x1) - f(y0, x0)
    return effects


def mediation_bootstrap(d, mediator_formula=MEDIATION_MEDIATOR_FORMULA, outcome_formula=MEDIATION_OUTCOME_FORMULA,
                        n_boot=2000, seed=0):
    """Task 4: pooling-stratified bootstrap of NDE / NIE / TE: point estimate, median and 95% percentile CI."""
    rng = np.random.default_rng(seed)
    point = mediation_effects(d, mediator_formula, outcome_formula)
    boot = pd.DataFrame([
        mediation_effects(d.groupby("pooling", group_keys=False)
                          .sample(frac=1, replace=True, random_state=int(rng.integers(10 ** 9))),
                          mediator_formula, outcome_formula)
        for _ in range(n_boot)])
    rows = []
    for (y0, y1, effect) in boot.columns:
        values = boot[(y0, y1, effect)]
        rows.append({"contrast": f"{y0:+.0f} -> {y1:+.0f}", "y0": y0, "y1": y1, "effect": effect,
                     "estimate": point[(y0, y1, effect)], "median": values.median(),
                     "ci_low": values.quantile(0.025), "ci_high": values.quantile(0.975),
                     "p_boot (two-sided)": min(1.0, 2 * min((values <= 0).mean(), (values >= 0).mean()))})
    return pd.DataFrame(rows)


def mediation_robustness(d):
    """
    Task 5: does the x:y interaction survive (a) quadratic terms, (b) RF as categorical, (c) HC3 standard errors?
    Also returns VIFs and Breusch-Pagan tests for the full and reduced outcome models.
    """
    from statsmodels.stats.outliers_influence import variance_inflation_factor
    from statsmodels.stats.diagnostic import het_breuschpagan

    xy = "scaled_saturation:RF_ordinal"
    variants = {
        "full (classical SE)": (MEDIATION_OUTCOME_FORMULA, "nonrobust"),
        "full (HC3)": (MEDIATION_OUTCOME_FORMULA, "HC3"),
        "full + RF^2": (MEDIATION_OUTCOME_FORMULA + " + I(RF_ordinal**2)", "nonrobust"),
        "full + RF^2 + x^2": (MEDIATION_OUTCOME_FORMULA + " + I(RF_ordinal**2) + I(scaled_saturation**2)",
                              "nonrobust"),
        "reduced (classical SE)": (MEDIATION_OUTCOME_FORMULA_REDUCED, "nonrobust"),
        "reduced (HC3)": (MEDIATION_OUTCOME_FORMULA_REDUCED, "HC3"),
        "reduced + RF^2": (MEDIATION_OUTCOME_FORMULA_REDUCED + " + I(RF_ordinal**2)", "nonrobust"),
        "reduced + RF^2 + x^2": (MEDIATION_OUTCOME_FORMULA_REDUCED + " + I(RF_ordinal**2) + I(scaled_saturation**2)",
                                 "nonrobust"),
        "additive (classical SE)": (MEDIATION_OUTCOME_FORMULA_ADDITIVE, "nonrobust"),
        "additive (HC3)": (MEDIATION_OUTCOME_FORMULA_ADDITIVE, "HC3"),
        "additive + RF^2": (MEDIATION_OUTCOME_FORMULA_ADDITIVE + " + I(RF_ordinal**2)", "nonrobust"),
        "additive + RF^2 + x^2": (MEDIATION_OUTCOME_FORMULA_ADDITIVE + " + I(RF_ordinal**2) + I(scaled_saturation**2)",
                                  "nonrobust"),
    }
    rows = []
    fits = {}
    for name, (formula, cov_type) in variants.items():
        fitted_model = smf.ols(formula, d).fit(cov_type=cov_type)
        fits[name] = fitted_model
        rows.append({"model": name, "formula": formula, "cov_type": cov_type, "n_params": len(fitted_model.params),
                     "x:y coef": fitted_model.params[xy], "x:y se": fitted_model.bse[xy],
                     "x:y p": fitted_model.pvalues[xy],
                     "RF^2 coef": fitted_model.params.get("I(RF_ordinal ** 2)", np.nan),
                     "RF^2 p": fitted_model.pvalues.get("I(RF_ordinal ** 2)", np.nan),
                     "x^2 coef": fitted_model.params.get("I(scaled_saturation ** 2)", np.nan),
                     "x^2 p": fitted_model.pvalues.get("I(scaled_saturation ** 2)", np.nan),
                     "R2": fitted_model.rsquared, "adj R2": fitted_model.rsquared_adj, "AIC": fitted_model.aic})
    interaction_table = pd.DataFrame(rows).set_index("model")

    # RF_ordinal has only 4 levels: with RF categorical the saturation slope is allowed to differ freely per level
    # (x:C(rf_level)) instead of linearly in RF (x:y). Compare against the same model with a single saturation slope.
    categorical_rows = []
    for label, base in [("with pooling", "scaled_delta ~ C(rf_level)*C(pooling) + scaled_saturation*C(pooling)"),
                        ("without pooling", "scaled_delta ~ C(rf_level)")]:
        common_slope = smf.ols(base + " + scaled_saturation", d).fit()
        slope_by_rf = smf.ols(base + " + scaled_saturation + scaled_saturation:C(rf_level)", d).fit()
        f_value, p_value, df_diff = slope_by_rf.compare_f_test(common_slope)
        row = {"model": f"RF categorical, {label}", "F (x slope differs by RF level)": f_value, "p": p_value,
               "df_num": df_diff, "df_den": slope_by_rf.df_resid, "n_params": len(slope_by_rf.params)}
        for level in sorted(d["rf_level"].unique()):
            contrast = np.zeros(len(slope_by_rf.params))
            names = list(slope_by_rf.params.index)
            contrast[names.index("scaled_saturation")] = 1.0
            interaction_name = f"scaled_saturation:C(rf_level)[T.{level}]"
            if interaction_name in names:
                contrast[names.index(interaction_name)] = 1.0
            test = slope_by_rf.t_test(contrast)
            row[f"x slope rf_level={level}"] = float(np.squeeze(test.effect))
            row[f"x slope p rf_level={level}"] = float(np.squeeze(test.pvalue))
        categorical_rows.append(row)
    categorical_table = pd.DataFrame(categorical_rows).set_index("model")

    vif_tables = []
    diagnostics_rows = []
    for name in ["full (classical SE)", "reduced (classical SE)", "additive (classical SE)"]:
        fitted_model = fits[name]
        exog = pd.DataFrame(fitted_model.model.exog, columns=fitted_model.model.exog_names)
        vif_tables.append(pd.DataFrame({
            "model": name, "term": exog.columns,
            "VIF": [variance_inflation_factor(exog.values, i) for i in range(exog.shape[1])]
        }))
        lm, lm_p, f_value, f_p = het_breuschpagan(fitted_model.resid, fitted_model.model.exog)
        influence = fitted_model.get_influence()
        cooks = influence.cooks_distance[0]
        diagnostics_rows.append({"model": name, "Breusch-Pagan LM": lm, "Breusch-Pagan LM p": lm_p,
                                 "Breusch-Pagan F": f_value, "Breusch-Pagan F p": f_p,
                                 "max Cook's distance": cooks.max(),
                                 "n Cook's distance > 4/n": int((cooks > 4 / len(d)).sum()),
                                 "max leverage": influence.hat_matrix_diag.max(),
                                 "n leverage > 2p/n": int((influence.hat_matrix_diag >
                                                           2 * len(fitted_model.params) / len(d)).sum())})
    vif_table = pd.concat(vif_tables, ignore_index=True)
    vif_table = vif_table[vif_table["term"] != "Intercept"]
    diagnostics_table = pd.DataFrame(diagnostics_rows).set_index("model")

    return interaction_table, categorical_table, vif_table, diagnostics_table, fits


