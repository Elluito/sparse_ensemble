def decide_type_of_model():
    df = pd.read_csv("diverse_pooling_pruning_saturation_per_seed_combined.csv", sep=",")

    df = df.rename(columns={
        "avg_depth_scaled_train_saturation": r"scaled_saturation",
        # "rf_level": "RF Level",
        # "delta_mean":r"$\Delta (Dense - Pruned)$",
        # "pooling":"Pooling method"
    })

    print("==================================================")
    print("  Not separating by model or Pruning rate")
    print("==================================================")

    # 1. Ensure RF is numeric/ordinal (e.g., 1, 2, 3, 4 or actual pixel sizes)
    df['RF_ordinal'] = df['rf_level'].astype(float)

    current_df = df[df["model"].str.contains("resnet50")]
    current_df = current_df[current_df["pruning_rate"] == 0.7]
    # 2. Model 1: Mediator Equation (a-paths)
    # Tests if RF, Pooling (4 levels), and their interaction influence Saturation
    model_simple = smf.ols(
        'scaled_saturation ~  RF_ordinal + C(pooling) + RF_ordinal * C(pooling)',
        data=current_df
    ).fit()

    model_complex = smf.ols(
        'scaled_saturation ~  RF_ordinal + C(pooling) ',
        data=current_df
    ).fit()
    # Compare AIC and BIC
    print(f"Simple Model  - AIC: {model_simple.aic:.2f}, BIC: {model_simple.bic:.2f}")
    print(f"Complex Model - AIC: {model_complex.aic:.2f}, BIC: {model_complex.bic:.2f}")

    print("###################################################")
    print("\t\t\tNow for delta (prunability)")
    print("=====================================================")
    model_simple = smf.ols(
        'delta~ scaled_saturation + RF_ordinal + C(pooling)',
        data=df
    ).fit()

    model_complex = smf.ols(
        'delta~ RF_ordinal * C(pooling) + scaled_saturation + RF_ordinal + C(pooling)',
        data=df
    ).fit()
    # Compare AIC and BIC
    print(f"Simple Model  - AIC: {model_simple.aic:.2f}, BIC: {model_simple.bic:.2f}")
    print(f"Complex Model - AIC: {model_complex.aic:.2f}, BIC: {model_complex.bic:.2f}")

