MEDIATION_MEDIATOR_FORMULA_ADDITIVE = "scaled_saturation ~ RF_ordinal + C(pooling)"
MEDIATION_OUTCOME_FORMULA_ADDITIVE = ("scaled_delta ~ scaled_saturation + RF_ordinal + C(pooling) + "
                                      "scaled_saturation:RF_ordinal")
MEDIATION_CONTRASTS = [(-1.0, 0.0), (0.0, 1.0), (-1.0, 1.0)]
# Curvature terms added to each outcome model for the robustness check of the NDE / NIE split
MEDIATION_CURVATURE_TERMS = " + I(RF_ordinal**2) + I(scaled_saturation**2)"


