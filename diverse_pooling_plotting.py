def dominance_analysis_pooling_methods_inblock():
    """
    dominance_analysis_pooling_methods() for ResNet-50 with the in-block depth-scaled saturation
    (layerX-Y-conv1/conv2, each scaled by its depth in the whole network) in place of the whole-model
    depth-scaled saturation. Results for every pruning rate are saved as sheets of one Excel file.
    """

    df_large = pd.read_csv("diverse_pooling_pruning_saturation_per_seed_combined.csv", sep=",")

    df_large = df_large.rename(columns={
        "avg_depth_scaled_train_saturation_inblock": r"scaled_saturation_inblock",
    })
    df_large["scaled_delta"] = df_large["delta"] / df_large["dense_acc"]
    df_large['RF_ordinal'] = df_large['rf_level'].astype(float)
    df_large["Kernel Size"] = df_large["RF_ordinal"] + 1

    df = df_large
    df["Kernel Size"] = (df["Kernel Size"] - df["Kernel Size"].mean()) / df["Kernel Size"].std()
    # In-block saturation only exists for ResNet-50 (NaN for VGG-19), so these statistics are over ResNet-50 rows.
    df["scaled_saturation_inblock"] = (df["scaled_saturation_inblock"] - df["scaled_saturation_inblock"].mean()) / \
                                      df["scaled_saturation_inblock"].std()

    df_prep1 = pd.get_dummies(df["pooling"], prefix="pool_", drop_first=True).astype(int)
    dummy_cols = [col for col in df_prep1.columns if "pool_" in col]
    df_prep2 = df[["Kernel Size", "scaled_saturation_inblock", "scaled_delta", "model", "pruning_rate"]]
    df = pd.concat([df_prep1, df_prep2], axis=1)

    predictors = {"Kernel Size": ["Kernel Size"], "pooling": dummy_cols,
                  "scaled_saturation_inblock": ["scaled_saturation_inblock"]}

    print("==================================================")
    print("          RESNET50 (in-block saturation)")
    print("==================================================")

    prs = [0.7, 0.8, 0.9]

    local_df = df[df["model"].str.contains("resnet50")]

    with pd.ExcelWriter('dominance_analysis_diverse_pooling_scaled_delta_resnet50_inblock_saturation.xlsx') as writer:
        for pr in prs:
            current_df = local_df[local_df["pruning_rate"] == pr]

            dominance_df = calculate_block_dominance(current_df, "scaled_delta", predictors)
            print("############################")
            print(f"      PR = {pr}                      ")
            print("############################")
            print(dominance_df)
            dominance_df.to_excel(writer, sheet_name=f'PR {pr}')


def analysis_pooling_methods():
    """
    This function is to analyze statistically the effect of different parts in prunability and saturation
    """

