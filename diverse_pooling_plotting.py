def extract_layer_stat(df,
                       epoch=19,
                       primary_metric=None,
                       stat='saturation',
                       state_mode="train") -> Tuple[pd.DataFrame, float]:
    """
    Extracts a specific statistic for a single epoch from a result dataframe as produced by the CSV-writer
    :param df: The dataframe produced by a CSVWriter
    :param epoch: Epoch to filter by
    :param primary_metric: Primary metric for performance evaluation (optional)
    :param stat: The statistic to match. Must be a substring matching all columns belonging to stat statistic like "saturation"
    :return: A dataframe with a single row, corresponding to the epoch containing only the columns that contain the substring
    described in the stat-parameter in their name. Second return value is the primary metric value
    """
    cols = list(df.columns)
    train_cols = [
        col for col in cols
        if state_mode in col and 'accuracy' not in col and stat in col
    ]
    if not np.any(epoch == df.index.values):
        raise ValueError(
            f'Epoch {epoch} could not be recoreded, dataframe has only the following indices: {df.index.values}'
        )
    epoch_df = df[df.index.values == epoch]
    pm = None if primary_metric is None else epoch_df[primary_metric].values[0]
    epoch_df = epoch_df[train_cols]
    return epoch_df, pm


def depth_scaled_saturation(layer_values):
    scaled_depth_indexes = np.array((range(1, len(layer_values) + 1))) / (len(layer_values))
    return layer_values * scaled_depth_indexes


def diverse_pooling_saturation_summary(base_folder, model_names, rf_levels=(1, 2, 3, 4), seeds=(0, 1, 2),
                                       dataset="cifar10", name="recording_diverse_pooling_100_no_ffcv",
                                       pruning_rate=0.0, epoch=0,
                                       save_path="saturation_diverse_pooling/diverse_pooling_train_saturation_summary.csv"):
    """
    Walks base_folder for the per-solution saturation CSVs produced by saturation_calculation.py
    (one row per file, named "<model>_<rf_level>_<dataset>_<name>_pr_<pruning_rate>_saturation_trained_seed_<seed>.csv"),
    and for each (model, rf_level, seed) observation extracts the train-time saturation of every
    layer at the given epoch via extract_layer_stat(), then averages across layers. Writes one row
    per observation (model, rf_level, seed, avg_train_saturation, std_train_saturation) to save_path.
    """
    rows = []
    missing = []
    for model in model_names:
        for rf_level in rf_levels:
            for seed in seeds:
                search_string = "{}/**/{}_{}_{}_{}_pr_{}_saturation_trained_seed_{}.csv".format(
                    base_folder, model, rf_level, dataset, name, pruning_rate, seed)
                matches = glob.glob(search_string, recursive=True)
                if not matches:
                    missing.append((model, rf_level, seed))
                    continue
                if len(matches) > 1:
                    print("WARNING: multiple files matched for {} rf_level={} seed={}, using the first one: {}".format(
                        model, rf_level, seed, matches))

                if model.startswith("resnet50_"):
                    model_type = "Resnet50"
                    pooling = model[len("resnet50_"):]
                elif model.startswith("vgg19_"):
                    model_type = "vgg19"
                    pooling = model[len("vgg19_"):]
                else:
                    print(f"WARNING: could not determine model type/pooling for model name '{model}'")
                    model_type = None
                    pooling = None

                df = pd.read_csv(matches[0], delimiter=";", index_col=0)
                epoch_df, _ = extract_layer_stat(df, epoch=epoch, primary_metric=None, stat="saturation",
                                                 state_mode="train")
                layer_values = epoch_df.values[0].astype(float)

                depth_scaled_layer_values = depth_scaled_saturation(layer_values)

                if model.startswith("resnet50_"):
                    in_block_layers_values = layer_values[in_block_layers_index]
                    depth_scaled_inblock_values = depth_scaled_saturation(in_block_layers_values)

                    out_block_layers_values = layer_values[out_of_block_layer_index]
                    depth_scaled_outblock_values = depth_scaled_saturation(out_block_layers_values)

                    rows.append({
                        "model": model,
                        "model type": model_type,
                        "pooling": pooling,
                        "rf_level": rf_level,
                        "seed": seed,
                        "n_layers": len(layer_values),
                        "avg_train_saturation": float(np.mean(layer_values)),
                        "std_train_saturation": float(np.std(layer_values, ddof=1)),
                        "avg_train_saturation_inblock": float(np.mean(in_block_layers_values)),
                        "std_train_saturation_inblock": float(np.std(in_block_layers_values, ddof=1)),
                        "avg_train_saturation_outlock": float(np.mean(out_block_layers_values)),
                        "std_train_saturation_outblock": float(np.std(out_block_layers_values, ddof=1)),
                        "avg_depth_scaled_train_saturation": float(np.mean(depth_scaled_layer_values)),
                        "std_depth_scaled_train_saturation": float(np.mean(depth_scaled_layer_values)),
                        "avg_depth_scaled_train_saturation_inblock": float(np.mean(depth_scaled_inblock_values)),
                        "std_depth_scaled_train_saturation_inblock": float(np.std(depth_scaled_inblock_values, ddof=1)),
                        "avg_depth_scaled_train_saturation_outlock": float(np.mean(depth_scaled_outblock_values)),
                        "std_depth_scaled_train_saturation_outblock": float(
                            np.std(depth_scaled_outblock_values, ddof=1))
                    })
                else:
                    rows.append({
                        "model": model,
                        "model type": model_type,
                        "pooling": pooling,
                        "rf_level": rf_level,
                        "seed": seed,
                        "n_layers": len(layer_values),
                        "avg_train_saturation": float(np.mean(layer_values)),
                        "std_train_saturation": float(np.std(layer_values, ddof=1)),
                        "avg_depth_scaled_train_saturation": float(np.mean(depth_scaled_layer_values)),
                        "std_depth_scaled_train_saturation": float(np.mean(depth_scaled_layer_values)),
                    })

    if missing:
        print("WARNING: {} missing (model, rf_level, seed) observations:".format(len(missing)))
        for m in missing:
            print("   ", m)

    summary_df = pd.DataFrame(rows)
    summary_df.to_csv(save_path, index=False)
    print("Wrote {} rows to {}".format(len(summary_df), save_path))
    return summary_df


